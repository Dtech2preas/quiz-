                    expl_we = f"1. Friction: f_k = μ_k × m × g = {muk:.2f} × {m_h:.0f} × 9.8 = {fk:.1f} N. 2. Net force: F_net = F_app - f_k = {f_app:.0f} - {fk:.1f} = {f_net:.1f} N. 3. W_net = F_net × Δx = {f_net:.1f} × {dx:.1f} = {w_net:.1f} J. 4. Work-Energy Theorem: W_net = 1/2 × m × vf² => vf = √(2 × W_net / m) = √(2 × {w_net:.1f} / {m_h:.0f}) = {corr_vf}."
