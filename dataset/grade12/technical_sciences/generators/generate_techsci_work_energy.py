    # 2. Conservation of Mechanical Energy on Rollercoaster / Pendulum Tracks:
    # mgh_i + 1/2 m vi² = mgh_f + 1/2 m vf² (isolated, frictionless)
    # Released from rest at height h1, finding speed at height h2: vf = sqrt(2g(h1 - h2))
    for h1 in [15.0, 20.0, 25.0, 30.0, 40.0, 50.0]:
        for h2 in [0.0, 5.0, 10.0, 15.0]:
            if counts["hard"] >= 200:
                break
            if h2 >= h1:
                continue
            dh = h1 - h2
            vf_track = math.sqrt(2.0 * 9.8 * dh)
            corr_vtrack = f"{vf_track:.2f} m·s⁻¹"
            wrs_vtrack = [
                f"{math.sqrt(2.0 * 9.8 * h1):.2f} m·s⁻¹ (ignored height h2, calculated speed at ground level)",
                f"{2.0 * 9.8 * dh:.2f} m·s⁻¹ (forgot square root)",
                f"{vf_track * 2:.2f} m·s⁻¹",
                f"{vf_track / 2:.2f} m·s⁻¹",
                f"{math.sqrt(9.8 * dh):.2f} m·s⁻¹",
                f"{vf_track + 4.0:.2f} m·s⁻¹",
                f"{vf_track * 1.4:.2f} m·s⁻¹"
            ]
            q_text_track = f"A roller-coaster cart is released from rest at point A (height h1 = {h1:.1f} m above the ground). It glides along a frictionless track down to point B at a height of h2 = {h2:.1f} m. Using the Principle of Conservation of Mechanical Energy, determine the speed of the cart at point B (g = 9.8 m·s⁻²):"
            expl_track = f"Mechanical energy is conserved: (E_p + E_k)_A = (E_p + E_k)_B => m × g × h1 + 0 = m × g × h2 + 1/2 × m × vf² => g × (h1 - h2) = 1/2 × vf² => vf = √(2 × g × Δh) = √(2 × 9.8 × {dh:.1f}) = {corr_vtrack}."
            add_q("hard", "Mechanical Energy Conservation", q_text_track, corr_vtrack, wrs_vtrack, "Evaluating", "Calculate speed from conservation of mechanical energy", expl_track)

    # 3. Machine Efficiency Calculations:
    # Given electric input power P_in (in kW), lifting mass m to height h in time t:
    # W_out = m * g * h; P_out = W_out / t; Efficiency = (P_out / P_in) * 100%
    for m_lift in [250.0, 500.0, 750.0, 1000.0, 1500.0, 2000.0]:
        for h_lift in [10.0, 15.0, 20.0, 25.0]:
            for t_lift in [15.0, 20.0, 25.0, 30.0]:
                for p_in_kw in [3.0, 4.0, 5.0, 7.5, 10.0, 15.0]:
                    if counts["hard"] >= 200:
                        break
                    w_out = m_lift * 9.8 * h_lift
                    p_out_w = w_out / t_lift
                    p_in_w = p_in_kw * 1000.0
                    eff_pct = (p_out_w / p_in_w) * 100.0
                    if eff_pct < 20.0 or eff_pct > 95.0:
                        continue # keep realistic engineering efficiency range (20% - 95%)
                    corr_eff = f"{eff_pct:.1f}%"
                    wrs_eff = [
                        f"{(p_in_w / p_out_w) * 100.0:.1f}% (inverted efficiency ratio)",
                        f"{eff_pct / 100.0:.4f}% (forgot to multiply by 100)",
                        f"{eff_pct * 2:.1f}%",
                        f"{eff_pct / 2:.1f}%",
                        f"100.0% (assumed zero energy loss)",
                        f"{eff_pct + 18.0:.1f}%",
                        f"{eff_pct * 1.3:.1f}%"
                    ]
                    q_text_eff = f"An electric hoist motor with an electrical input power rating of {p_in_kw:.1f} kW ({p_in_kw * 1000:.0f} W) lifts a load of mass {m_lift:.0f} kg vertically through a height of {h_lift:.1f} m in a time of {t_lift:.1f} seconds. Taking g = 9.8 m·s⁻², calculate the overall operating EFFICIENCY of the hoist system:"
                    expl_eff = f"1. Useful work output: W_out = m × g × h = {m_lift:.0f} × 9.8 × {h_lift:.1f} = {w_out:.1f} J. 2. Useful power output: P_out = W_out / t = {w_out:.1f} J / {t_lift:.1f} s = {p_out_w:.1f} W. 3. Efficiency = (P_out / P_in) × 100% = ({p_out_w:.1f} W / {p_in_w:.0f} W) × 100% = {corr_eff}."
                    add_q("hard", "Efficiency Calculations", q_text_eff, corr_eff, wrs_eff, "Evaluating", "Calculate percentage efficiency of industrial electric hoist", expl_eff)

    return questions

